export function getProperty(slug: string): Property | undefined {
  return PROPERTIES.find((p) => p.slug === slug);
}

export function getSimilarProperties(property: Property, limit = 3): Property[] {
  return PROPERTIES.filter((p) => p.slug !== property.slug)
    .map((p) => ({
      property: p,
      score:
        (p.type === property.type ? 2 : 0) +
        (p.country === property.country ? 1 : 0) +
        (Math.abs(p.price - property.price) < 400000 ? 2 : 0) +
        (p.beds === property.beds ? 1 : 0),
    }))
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((s) => s.property);
}

